export const questions = new Hono<AppEnv>()

// requireAuth is applied per-route (not via `.use('*', ...)`) — see the
// comment in src/routes/sources.ts for why a wildcard here would leak
// onto unrelated public routes mounted alongside this sub-app.

const NO_SOURCE_MESSAGE =
  'I could not find an answer in the approved materials for this course. Please check with your instructor.'

const FALLBACK_NOTE =
  'This is a deterministic keyword search over approved course materials, not an AI-generated explanation.'

const AI_NOTE =
  'This answer was generated by AI using only the cited approved course materials. Check the cited sources.'

type AiAttempt = { answer: AiAnswer; failure: null } | { answer: null; failure: AiFailureReason; error?: string }

/**
 * Tries the AI path (PRD FR-04/FR-07/NFR-06). Never throws: any problem is
 * returned as a failure reason and the caller uses the keyword fallback (FR-08).
 */
async function tryAiAnswer(env: Env, db: D1Database, courseId: string, question: string, matches: FallbackMatch[]): Promise<AiAttempt> {
  if (env.AI_ENABLED !== 'true' || !env.AI) return { answer: null, failure: 'disabled' }
  try {
    const used = await tryConsumeAiBudget(db, courseId, Number(env.AI_DAILY_BUDGET_PER_COURSE))
    if (used === null) return { answer: null, failure: 'over_budget' }
    const answer = await generateCitedAnswer(env.AI, env.AI_MODEL, question, matches, Number(env.AI_TIMEOUT_MS))
    return { answer, failure: null }
  } catch (err) {
    if (err instanceof AiAnswerError) return { answer: null, failure: err.reason, error: err.message }
    return { answer: null, failure: 'model_error', error: err instanceof Error ? err.message : String(err) }
  }
}

/** Instructors can read any question; a student may only read their own. */
export function canViewQuestion(user: AuthUser, question: Pick<Question, 'studentId'>): boolean {
  return user.role === 'instructor' || question.studentId === user.id
}

questions.post('/questions', requireAuth, requireRole('student'), async (c) => {
  try {
    const body = await readJsonBody(c)
    const courseId = requireNonEmptyString(body.courseId, 'courseId')
    const questionText = requireNonEmptyString(body.questionText, 'questionText')
    if (questionText.length < MIN_QUESTION_LENGTH || questionText.length > MAX_QUESTION_LENGTH) {
      throw new ValidationError(
        `questionText must be between ${MIN_QUESTION_LENGTH} and ${MAX_QUESTION_LENGTH} characters.`,
      )
    }

    const user = c.get('user')
    const db = getDb(c.env)
    const now = new Date().toISOString()

    const question = await createQuestion(db, {
      id: crypto.randomUUID(),
      courseId,
      studentId: user.id,
      questionText,
      createdAt: now,
      updatedAt: now,
    })

    const [approvedSources, approvedChunks] = await Promise.all([
      listApprovedSourcesByCourse(db, courseId),
      listApprovedChunksByCourse(db, courseId),
    ])
    const keywordMatches = findChunkMatches(approvedSources, approvedChunks, questionText)

    // FR-06: no relevant source means no model call and no substantive answer.
    const ai: AiAttempt =
      keywordMatches.length === 0
        ? { answer: null, failure: 'not_covered' }
        : await tryAiAnswer(c.env, db, courseId, questionText, keywordMatches)

    // FR-06 also applies when the model read the passages and found they do not
    // answer the question: say so, instead of listing loosely matched sources.
    const matches = ai.failure === 'not_covered' ? [] : keywordMatches
    const noSourceFound = matches.length === 0

    const citedMatches = ai.answer ? ai.answer.citedIndexes.map((i) => matches[i]) : matches
    const mode = ai.answer ? 'ai' : 'fallback'

    const answerContent = noSourceFound
      ? NO_SOURCE_MESSAGE
      : ai.answer
        ? ai.answer.content
        : [
            'Based on the approved course materials, the following source(s) appear relevant to your question:',
            '',
            ...matches.map(
              (match, index) =>
                `${index + 1}. ${match.source.title}${match.location ? ` (${match.location})` : ''} — "${match.excerpt}"`,
            ),
          ].join('\n')

    // AI decision log: outcome, tokens and timing only — never question or answer text (NFR-11).
    log(ai.answer || noSourceFound ? 'info' : 'warn', 'ai_answer', {
      correlationId: c.get('correlationId'),
      courseId,
      questionId: question.id,
      questionLength: questionText.length,
      retrievedSources: matches.length,
      mode,
      noSourceFound,
      fallbackReason: ai.answer ? null : ai.failure,
      error: ai.answer ? null : (ai.error ?? null),
      model: ai.answer?.model ?? null,
      citedSources: citedMatches.length,
      promptTokens: ai.answer?.usage.promptTokens ?? null,
      completionTokens: ai.answer?.usage.completionTokens ?? null,
      aiLatencyMs: ai.answer?.latencyMs ?? null,
    })

    const answerCreatedAt = new Date().toISOString()

    const { answer, citations } = await createAnswerWithCitations(db, {
      id: crypto.randomUUID(),
      questionId: question.id,
      content: answerContent,
      mode,
      noSourceFound,
      createdAt: answerCreatedAt,
      citations: citedMatches.map((match) => ({
        id: crypto.randomUUID(),
        sourceId: match.source.id,
        excerpt: match.excerpt,
        location: match.location ?? null,
        score: match.score,
        createdAt: answerCreatedAt,
      })),
    })

    const finalStatus: QuestionStatus = noSourceFound ? 'no_source_found' : 'answered'
    const updatedQuestion = await updateQuestionStatus(db, question.id, finalStatus, new Date().toISOString())

    return sendData(c, 201, {
      question: updatedQuestion ?? question,
      answer,
      // Same shape as GET /v1/questions/:id, so clients can show source titles.
      citations: citations.map((citation, i) => ({
        ...citation,
        sourceTitle: citedMatches[i].source.title,
        sourceUrl: citedMatches[i].source.sourceUrl,
      })),
      note: mode === 'ai' ? AI_NOTE : FALLBACK_NOTE,
      generation: { mode, fallbackReason: ai.answer ? null : ai.failure, model: ai.answer?.model ?? null },
    })
  } catch (err) {
    if (err instanceof ValidationError) return sendError(c, 400, 'VALIDATION_ERROR', err.message)
    throw err
  }
})

questions.get('/questions/:id', requireAuth, async (c) => {
  const id = c.req.param('id')
  if (!id) return sendError(c, 400, 'VALIDATION_ERROR', 'id is required.')

  const db = getDb(c.env)

  const question = await findQuestionById(db, id)
  if (!question) return sendError(c, 404, 'NOT_FOUND', 'Question not found.')

  const user = c.get('user')
  if (!canViewQuestion(user, question)) {
    return sendError(c, 403, 'FORBIDDEN', 'You do not have access to this question.')
  }

  const [{ answer, citations }, replies] = await Promise.all([
    findAnswerWithCitationsByQuestionId(db, question.id),
    listRepliesForQuestion(db, question.id),
  ])

  // The student who asked has now seen any new instructor replies.
  if (question.studentId === user.id && replies.some((r) => r.readAt === null)) {
    await markRepliesRead(db, question.id, new Date().toISOString())
  }

  return sendData(c, 200, { question, answer, citations, replies })
})
